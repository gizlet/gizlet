// Postgres migrations for accounts (migrations/pg/*.sql, applied in name order).
//
//   node scripts/pg.ts migrate            # apply pending migrations to $DATABASE_URL
//   node scripts/pg.ts generate <name>    # write the next migration for changes to src/auth.ts
//   node scripts/pg.ts serve <port> [dir] # Postgres (PGlite) for local runs: in memory, or kept in <dir>
//
// `generate` applies the existing migrations to an in-memory database and asks Better Auth
// what its options in src/auth.ts still need.
import { readdir, readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { PGlite } from "@electric-sql/pglite";
import { PGLiteSocketServer } from "@electric-sql/pglite-socket";
import { getMigrations } from "better-auth/db/migration";
import pg from "pg";
import { authOptions } from "../src/auth.ts";

const DIR = join(import.meta.dirname, "..", "migrations", "pg");

async function migrate(pool: pg.Pool): Promise<string[]> {
  await pool.query("CREATE TABLE IF NOT EXISTS _migrations (name text PRIMARY KEY, applied_at timestamptz NOT NULL DEFAULT now())");
  const done = new Set((await pool.query<{ name: string }>("SELECT name FROM _migrations")).rows.map((r) => r.name));
  const applied: string[] = [];
  for (const name of (await readdir(DIR)).filter((f) => f.endsWith(".sql")).sort()) {
    if (done.has(name)) continue;
    const client = await pool.connect();
    try {
      await client.query("BEGIN");
      await client.query(await readFile(join(DIR, name), "utf8"));
      await client.query("INSERT INTO _migrations (name) VALUES ($1)", [name]);
      await client.query("COMMIT");
      applied.push(name);
    } catch (e) {
      await client.query("ROLLBACK");
      throw new Error(`${name}: ${e instanceof Error ? e.message : String(e)}`);
    } finally {
      client.release();
    }
  }
  return applied;
}

async function serve(port: number, maxConnections = 8, dataDir?: string): Promise<{ url: string; stop: () => Promise<void> }> {
  const db = await PGlite.create(dataDir);
  const server = new PGLiteSocketServer({ db, port, host: "127.0.0.1", maxConnections });
  await server.start();
  return {
    url: `postgresql://postgres:postgres@127.0.0.1:${port}/postgres?sslmode=disable`,
    stop: async () => {
      await server.stop();
      await db.close();
    },
  };
}

const [command, arg, dir] = process.argv.slice(2);
if (command === "migrate") {
  const url = process.env.DATABASE_URL;
  if (!url) throw new Error("DATABASE_URL is not set");
  const pool = new pg.Pool({ connectionString: url, max: 1 });
  try {
    const applied = await migrate(pool);
    console.log(applied.length ? `applied ${applied.join(", ")}` : "no pending migrations");
  } finally {
    await pool.end();
  }
} else if (command === "generate") {
  if (!arg || !/^[a-z0-9_]+$/.test(arg)) throw new Error("usage: node scripts/pg.ts generate <snake_case_name>");
  const db = await serve(40000 + Math.floor(Math.random() * 20000), 1);
  const pool = new pg.Pool({ connectionString: db.url, max: 1 });
  try {
    await migrate(pool);
    const env = { SITE_ORIGIN: "https://gizlet.io", API_ORIGIN: "https://api.gizlet.io", GITHUB_API: "https://api.github.com", BETTER_AUTH_SECRET: "x".repeat(32), MAIL_FROM: "x" };
    const plan = await getMigrations(authOptions(env, pool), { throwOnUnsafe: true });
    const sql = (await plan.compileMigrations()).trim();
    if (!sql) {
      console.log("the schema is up to date");
    } else {
      const next = String((await readdir(DIR)).filter((f) => f.endsWith(".sql")).length + 1).padStart(4, "0");
      const file = join(DIR, `${next}_${arg}.sql`);
      await writeFile(file, `-- Generated by scripts/pg.ts from the Better Auth options in src/auth.ts.\n${sql}\n`);
      console.log(`wrote ${file}`);
    }
  } finally {
    await pool.end();
    await db.stop();
  }
} else if (command === "serve") {
  const db = await serve(Number(arg ?? 54320), 8, dir);
  console.log(db.url);
  const stop = () => db.stop().then(() => process.exit(0));
  process.on("SIGTERM", stop);
  process.on("SIGINT", stop);
} else {
  console.error("usage: node scripts/pg.ts migrate | generate <name> | serve <port>");
  process.exit(2);
}
